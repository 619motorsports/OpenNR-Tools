double gear_ratio(int index) {
    if (index < 0) index = 0;
    if (index >= kGearRatioTableSize) index = kGearRatioTableSize - 1;
    const TeethPair& p = kTable[static_cast<std::size_t>(index)];
    if (p.denom == 0) return 0.0;
    return static_cast<double>(p.numer) / static_cast<double>(p.denom);
}

